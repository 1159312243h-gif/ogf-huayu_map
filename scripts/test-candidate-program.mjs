import assert from "node:assert/strict";
import {promises as fs} from "node:fs";
import os from "node:os";
import path from "node:path";
import {fileURLToPath} from "node:url";
import {spawnSync} from "node:child_process";
import {refreshCandidateProgram} from "./update-all-data.mjs";
const root=await fs.mkdtemp(path.join(os.tmpdir(),"huayu-candidate-program-"));
const source=path.join(root,"source"),candidate=path.join(root,"candidate");
await fs.mkdir(source);await fs.mkdir(candidate);
const manifest={files:[{path:"app.js",kind:"code"},{path:"terrain-helper.js",kind:"code"},{path:"transit-preload.json",kind:"data"}]};
await fs.writeFile(path.join(source,"desktop-assets.json"),JSON.stringify(manifest));
for(const [name,body] of [["app.js","new app"],["_worker.js","new worker"],["terrain-helper.js","new height helper"],["transit-preload.json","published data"]])await fs.writeFile(path.join(source,name),body);
await fs.writeFile(path.join(candidate,"app.js"),"old app");await fs.writeFile(path.join(candidate,"_worker.js"),"old worker");
await fs.writeFile(path.join(candidate,"transit-preload.json"),"complete new candidate data");
await fs.writeFile(path.join(candidate,"unrelated-checkpoint.json"),"complete raw source checkpoint");
const first=await refreshCandidateProgram(candidate,source);
for(const [name,body] of [["app.js","new app"],["_worker.js","new worker"],["terrain-helper.js","new height helper"]])assert.equal(await fs.readFile(path.join(candidate,name),"utf8"),body);
assert.equal(await fs.readFile(path.join(candidate,"transit-preload.json"),"utf8"),"complete new candidate data");
assert.equal(await fs.readFile(path.join(candidate,"unrelated-checkpoint.json"),"utf8"),"complete raw source checkpoint");
assert.equal(await refreshCandidateProgram(candidate,source),first,"unchanged code reuses the same step fingerprint");
await fs.writeFile(path.join(source,"terrain-helper.js"),"newer height helper");
assert.notEqual(await refreshCandidateProgram(candidate,source),first,"a shared helper change invalidates old build steps even before a manifest update");
assert.equal(await fs.readFile(path.join(candidate,"terrain-helper.js"),"utf8"),"newer height helper");
manifest.files.push({path:"../outside.js",kind:"code"});await fs.writeFile(path.join(source,"desktop-assets.json"),JSON.stringify(manifest));
await assert.rejects(refreshCandidateProgram(candidate,source),/Unsafe/);
console.log("Candidate program refresh passed: resumed program/Worker/shared helpers are current, complete data and raw checkpoints stay intact, code changes invalidate steps and paths stay scoped.");

const missingCandidate=path.join(root,"missing-generation","transit-preload.json");
const run=spawnSync(process.execPath,[fileURLToPath(new URL("./test-transit-display.mjs",import.meta.url)),missingCandidate],{encoding:"utf8",windowsHide:true});
assert.notEqual(run.status,0);
assert.ok(run.stderr.includes(path.join(root,"missing-generation","app.js")),"candidate tests must reject the specified incomplete generation, never fall back to published data");
console.log("Candidate gate passed: the actual display regression reads the requested candidate runtime and rejects an incomplete generation.");
